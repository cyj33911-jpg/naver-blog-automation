def load_custom_templates():
    """저장된 커스텀 템플릿 로드"""
    if not os.path.exists(CUSTOM_TEMPLATES_FILE):
        return {}
    try:
        with open(CUSTOM_TEMPLATES_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def save_custom_templates(templates):
    """커스텀 템플릿 저장"""
    with open(CUSTOM_TEMPLATES_FILE, "w", encoding="utf-8") as f:
        json.dump(templates, f, ensure_ascii=False, indent=2)


def add_custom_template(name, structure):
    """커스텀 템플릿 추가"""
    templates = load_custom_templates()
    templates[name] = {
        "description": "사용자 정의 템플릿",
        "structure": structure,
    }
    save_custom_templates(templates)


def delete_custom_template(name):
    """커스텀 템플릿 삭제"""
    templates = load_custom_templates()
    if name in templates:
        del templates[name]
        save_custom_templates(templates)


def get_all_templates():
    """기본 + 커스텀 템플릿 통합 반환"""
    all_templates = dict(BUILTIN_TEMPLATES)
    custom = load_custom_templates()
    for name, data in custom.items():
        all_templates[f"[커스텀] {name}"] = data
    return all_templates


def get_all_template_names():
    """전체 템플릿 이름 목록"""
    return list(get_all_templates().keys())


def get_template_prompt(template_name):
    """템플릿 이름으로 프롬프트용 구조 텍스트 반환"""
    all_templates = get_all_templates()
    template = all_templates.get(template_name)
    if not template or not template["structure"]:
        return ""
    return template["structure"]
